#!/usr/bin/env python3
"""Gera projeto/MEMORIAL_UCB.md com os números tirados dos resultados (nunca digitados à mão; ver ERROS.md nº 21).

Fontes: resultados_ucb_ponte.json e saida_calculo_ucb.txt (calculo_ucb.py), montagem.json (gerar_montagem.py),
resultados_ucb.json (estudo_ucb.py) e a saída de verificar_modelo.py.
"""
import json, math, os, subprocess, sys
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, D)
import estudo_geometrias as eg

G = 9.80665
r = json.load(open(os.path.join(D, "resultados_ucb_ponte.json")))
mo = json.load(open(os.path.join(D, "montagem.json")))
res, tipos, C = mo["resumo"], mo["tipos"], mo["const"]
est = json.load(open(os.path.join(D, "resultados_ucb.json")))
saida = open(os.path.join(D, "saida_calculo_ucb.txt")).read()
verif = subprocess.run([sys.executable, os.path.join(D, "verificar_modelo.py")], capture_output=True, text=True).stdout

def f(x, n=5):
    return f"{x:.{n}f}".replace(".", ",")

linhas = {x["id"]: x for x in r["linhas"]}
P = r["P_final"]; M = res["massa_g"]
TAU = 2.0; FC90 = 0.25 * eg.FC
I3 = eg.B * (3 * eg.T) ** 3 / 12
Pe100 = math.pi ** 2 * eg.E * I3 / 100.0 ** 2
R_apoio = P * G / 4; A_apoio = eg.B * 10.0

# modos de colapso em ordem
modos = [("Barras (pior: " + min(r["linhas"], key=lambda x: x["P_kgf"])["id"] + ", " +
          min(r["linhas"], key=lambda x: x["P_kgf"])["modo"] + ")", r["P_barra"]),
         ("Ligações coladas das barras de alma (chapas, 40 mm)", r["P_lig"]),
         ("Mini-treliça do ponto de carga (pior parte: ligações)", r["P_tr"]),
         ("Cola dos consolos que seguram a mini-treliça", r["P_tr_tau"])]
modos.sort(key=lambda t: t[1])

# estudo: melhor de cada tipo (eficiência teórica)
melhor = {}
for x in est:
    if x["tipo"] not in melhor or x["ef"] > melhor[x["tipo"]]["ef"]: melhor[x["tipo"]] = x

top = sorted(r["linhas"], key=lambda x: x["P_kgf"])[:8]
L = []
w = L.append
w("# Memorial de cálculo: ponte de palito UCB 2026/2 (Pratt, 8 painéis, vão de 800 mm)")
w("")
w("Gerado por `projeto/gerar_memorial_ucb.py` a partir dos resultados dos scripts. Números com 5 casas decimais.")
w("Regras da competição: `docs/requisitos.md`. Erros já cometidos e como evitá-los: `ERROS.md`.")
w("")
w("## 1. Objetivo")
w("")
w("Ponte só de palito de picolé e cola branca para a IV Competição da Ponte de Palito de Picolé (UCB, 2026/2).")
w("A meta da equipe é **garantir o bônus de 30 kgf** com folga, numa ponte simples de construir em dois dias.")
w("A nota premia a carga por peso: NF = (carga de ruptura ÷ peso) × 0,8 + estética × 0,2.")
w("")
w("## 2. Regras que definem o projeto")
w("")
w("| regra | valor exigido | projeto | situação |")
w("|---|---|---|---|")
w(f"| Vão livre | 800 mm | 800 mm entre as bordas dos blocos | ✓ |")
w(f"| Comprimento total | 1000 a 1100 mm | 1020 mm | ✓ (ver nota) |")
w(f"| Largura | 200 a 250 mm | 220 mm | ✓ |")
w(f"| Altura | até 300 mm | 116,4 mm | ✓ |")
w(f"| Peso | até 1 kg | {f(M)} g (estimado) | ✓ |")
w(f"| Palitos por seção | até 5 | 3 | ✓ |")
w(f"| Materiais | palito e cola branca | palito e cola branca, inclusive os espaçadores provisórios | ✓ |")
w(f"| Ligações | encaixe ou sobreposição | sobreposição (chapas coladas nas duas faces) | ✓ |")
w(f"| Apoio | só no topo dos blocos, sem usar a face vertical | a ponta da ponte apoia no rolete pela transversina do nó b0 | ✓ |")
w("")
w("**Nota sobre o comprimento.** O regulamento pede comprimento de 100 a 110 cm e, no item dos apoios, “prolongamento")
w("de até 10 cm de cada lado”. As duas frases só fecham juntas com exatamente 100 cm, e o regulamento não tem tolerância.")
w(f"Adotamos {f(C['VAO'] + 2 * C['BAL'], 0)} mm ({f(C['BAL'], 0)} mm além de cada apoio), 20 mm acima do mínimo. **Confirmar com a organização**;")
w("se exigirem no máximo 100 mm de cada lado, basta lixar 10 mm de cada ponta do banzo inferior (fica 1000 mm, sem folga).")
w("")
w("## 3. Material (valores com origem)")
w("")
w("| propriedade | valor | origem |")
w("|---|---|---|")
w(f"| Palito | {f(eg.B, 1)} × {f(eg.T, 1)} × 110 mm, parte reta útil 101,6 mm | palito tradicional (o regulamento cita cerca de 115 × 8,4 mm); espessura e comprimento **[PENDENTE: medir o lote comprado]** |")
w(f"| Módulo de elasticidade E | {f(eg.E, 0)} MPa | valor usual em pontes de palito; abaixo do Pinus elliottii da NBR 7190 (conservador) |")
w(f"| Resistência à tração f_t | {f(eg.FT, 2)} MPa | AVILA (2009), média de 8 palitos (fonte secundária) |")
w(f"| Resistência à compressão f_c0 | {f(eg.FC, 1)} MPa | ABNT NBR 7190, Pinus elliottii |")
w(f"| Compressão normal às fibras f_c90 | {f(FC90, 1)} MPa | 0,25 × f_c0 (ABNT NBR 7190) |")
w(f"| Densidade | 560 kg/m³ | ABNT NBR 7190, Pinus elliottii |")
w(f"| Cisalhamento da cola PVA τ | {f(TAU, 1)} MPa | **estimativa conservadora [PENDENTE ensaio]** |")
w(f"| Consumo de cola | 200 g/m² | ficha técnica Cascola Cascorez Extra (Henkel) |")
w("")
w("## 4. Escolha do formato")
w("")
w(f"O script `estudo_ucb.py` comparou Pratt, Howe, Warren e Parker com 6 a 12 painéis e várias alturas, dimensionando cada barra")
w(f"com o menor número de palitos (1 a 5) e estimando o peso da ponte inteira. Foram {len(est)} combinações viáveis.")
w("Melhor resultado teórico de cada tipo (carga-alvo, peso e eficiência são do modelo simplificado, sem emendas nem chapas reais):")
w("")
w("| tipo | painéis | altura (mm) | carga-alvo (kgf) | peso (g) | kgf por kg | barra mais longa (mm) | palitos por barra |")
w("|---|---|---|---|---|---|---|---|")
for t in ("pratt", "parker", "warren", "howe"):
    x = melhor[t]
    w(f"| {t.capitalize()} | {x['paineis']} | {x['h']} | {x['kg']} | {f(x['massa'])} | {f(x['ef'])} | {f(x['Lmax'])} | {x['nmax']} |")
w("")
w("Os formatos mais eficientes no papel usam barras de 5 palitos com até 180 mm, muitas emendas e ângulos diferentes em cada nó.")
w("Com dois dias até a entrega e a meta de garantir o bônus, escolhemos a **Pratt de 8 painéis de 100 mm e 100 mm de altura**:")
w("")
w("- todo montante tem 100 mm entre eixos e cabe num palito;")
w("- as diagonais são todas iguais (141,42136 mm, 45°), então há poucos tipos de corte;")
w("- todas as barras têm 3 palitos, logo as chapas das duas faces ficam planas;")
w("- na Pratt as diagonais trabalham tracionadas (com a carga no centro) e as barras comprimidas são curtas.")
w("")
w("## 5. Geometria adotada")
w("")
w("| item | valor |")
w("|---|---|")
w("| Treliças | 2 treliças Pratt, 8 painéis de 100 mm, altura entre eixos de 100 mm |")
w("| Barras | 3 palitos colados face a face (seção 8,4 × 6,0 mm). Banzos contínuos com emendas desencontradas entre as camadas |")
w("| Nós | chapas de palito nas duas faces (2 mm cada); cada ponta de barra entra 40 mm na chapa |")
w(f"| Largura | {f(C['LARG'], 0)} mm entre as faces externas das treliças |")
w("| Travamento | transversinas inferiores nos nós b0 a b8 (menos b4), escoras superiores nos nós t1 a t7 e diagonais em zigue-zague em cima e embaixo |")
w("| Ponto de carga | mini-treliça transversal no meio do vão (altura 70 mm), apoiada em consolos colados nas faces internas do nó b4; a haste de aço é pendurada no nó do meio |")
w("")
w("Conferência do modelo físico peça por peça (`verificar_modelo.py`):")
w("")
w("```")
w(verif.strip())
w("```")
w("")
w("## 6. Hipóteses de cálculo")
w("")
w("- Treliça plana com nós articulados, resolvida pelo método da rigidez direta (`calculo_ucb.py`, que usa o solver da skill `analise-trelica`).")
w("- Carga total P no meio do vão: P/2 em cada treliça, no nó b4. Peso próprio desprezado (ver item 11).")
w("- **Envoltória**: carga no centro e carga deslocada um painel para cada lado (a haste pode não ficar exatamente no meio).")
w("  Cada caso usa a resistência do seu próprio sinal (tração ou compressão).")
w("- Tração: f_t × área dos palitos efetivos. Barras com emenda (banzos contínuos e diagonais maiores que um palito) contam 2 dos 3 palitos.")
w("- Compressão: menor entre a flambagem de Euler (comprimento entre nós, K = 1, eixo mais fraco) e o esmagamento f_c0 × área.")
w("  Os nós do banzo superior são travados fora do plano pelas escoras e pelo contraventamento. Nas emendas comprimidas o topo dos palitos encosta.")
w("- Nenhum coeficiente reduz as resistências: o resultado é uma **estimativa da carga de colapso**, comparada depois com os 30 kgf do bônus.")
w("")
w("## 7. Esforços, resistências e carga de colapso de cada barra")
w("")
w("Saída de `calculo_ucb.py` para P = 1000 N (N > 0 tração, N < 0 compressão; “N desloc” é o caso deslocado que governa):")
w("")
w("```")
w(saida.split("\nLIGAÇÕES")[0].strip())
w("```")
w("")
w("As oito barras mais críticas:")
w("")
w("| barra | L (mm) | N centro (N/1000 N) | N deslocado | resistência (N) | colapso (kgf) | modo |")
w("|---|---|---|---|---|---|---|")
for x in top:
    w(f"| {x['id']} | {f(x['L_mm'])} | {f(x['N'])} | {f(x['N_desloc'])} | {f(x['R'])} | {f(x['P_kgf'])} | {x['modo']} |")
w("")
w("### Conferência à mão")
w("")
w("- **Equilíbrio**: com 500 N por treliça no centro, cada apoio recebe 250 N (a saída mostra 250 + 250 = 500 N e resíduo 0).")
w("- **Banzo superior no meio** (seção pelo nó t4): M = 250 N × 400 mm = 100000 N·mm; N = M ÷ 100 mm = 1000 N de compressão. Igual à tabela.")
w("- **Diagonal da ponta**: a força vertical de 250 N passa por uma barra a 45°: N = 250 × √2 = 353,55339 N. Igual à tabela.")
w(f"- **Flambagem de t3-t4**: I = 8,4 × 6³ ÷ 12 = {f(I3)} mm⁴; P_cr = π² × {f(eg.E, 0)} × {f(I3)} ÷ 100² = {f(Pe100)} N.")
w(f"  A barra recebe 1000 N quando P = 1000 N, então o colapso é {f(Pe100)} ÷ {f(G)} = {f(Pe100 / G)} kgf. Igual à tabela.")
w("")
w("## 8. Ligações coladas")
w("")
w("Cada ponta de barra de alma entra 40 mm entre as chapas das duas faces. Resistência da cola de uma ponta:")
w(f"R = τ × 2 faces × 8,4 mm × 40 mm = {f(TAU, 1)} × 2 × 8,4 × 40 = {f(TAU * 2 * 8.4 * 40)} N.")
w(f"Comparada à barra mais carregada, a ligação leva a ponte ao colapso com **{f(r['P_lig'])} kgf**.")
w("Os banzos passam inteiros pelos nós e não dependem das chapas.")
w("")
w("## 9. Ponto de carga: mini-treliça e consolos")
w("")
w("O regulamento põe a carga no centro, numa haste de aço de 8 mm pendurada na ponte (figura 5 do regulamento).")
w("Uma haste ou viga de palito de 200 mm entre as treliças, carregada no meio, teria emendas perto do meio do vão.")
w("Por isso a carga entra numa mini-treliça transversal de 70 mm de altura, que se apoia em consolos colados nos nós b4 das duas treliças.")
w("")
w("```")
w(("MINI-TRELIÇA" + saida.split("MINI-TRELIÇA")[1].split("\n\n")[0]).strip())
w("```")
w("")
w(f"Consolo: 30 × 8,4 mm colados na chapa interna de cada treliça; R = {f(TAU, 1)} × 30 × 8,4 = {f(TAU * 30 * 8.4)} N por lado;")
w(f"os dois juntos seguram 2 × {f(TAU * 30 * 8.4)} ÷ {f(G)} = **{f(r['P_tr_tau'])} kgf**. É o elo mais fraco calculado, e depende do τ da cola, que ainda é estimado.")
w("")
w("## 10. Apoio nos blocos")
w("")
w("Pela figura 4 do regulamento, o rolete fica na quina interna do bloco, embaixo do nó da ponta da treliça.")
w(f"Na carga de colapso calculada, cada ponta de treliça recebe R = P/4 = {f(R_apoio)} N, sobre a transversina do nó b0")
w(f"(8,4 mm × 10 mm de banzo com chapas = {f(A_apoio)} mm²): σ = {f(R_apoio / A_apoio)} MPa, contra f_c90 = {f(FC90)} MPa")
w(f"(fator {f(FC90 / (R_apoio / A_apoio))}). A ponte não usa a face vertical dos blocos.")
w("")
w("## 11. Carga de colapso estimada e eficiência")
w("")
w("| modo de colapso | carga (kgf) |")
w("|---|---|")
for nome, v in modos:
    w(f"| {nome} | {f(v)} |")
w("")
w(f"- **Carga de colapso estimada: {f(P)} kgf.**")
w(f"- Fator sobre o bônus: {f(P)} ÷ 30 = **{f(P / 30)}**.")
w(f"- Peso estimado da ponte: {f(M)} g (palitos e cola seca), {f(1000 - M)} g abaixo do limite de 1 kg.")
w(f"- Relação carga ÷ peso estimada: {f(P)} ÷ {f(M / 1000)} = {f(P / (M / 1000))} kgf/kg; parcela de 80% da nota: {f(0.8 * P / (M / 1000))}.")
w(f"- Peso próprio ÷ carga de colapso: {f(100 * (M / 1000) / P)}%. Por isso foi desprezado.")
w(f"- A carga inicial do ensaio (10 kg) é {f(1000 / P)}% da carga de colapso estimada.")
w("")
w("## 12. Quantitativo (do modelo físico, peça por peça)")
w("")
w("| item | quantidade |")
w("|---|---|")
w(f"| Peças da ponte | {res['pecas']} peças em {len(tipos)} tipos (códigos no manual de corte) |")
w(f"| Espaçadores provisórios | {res['pecas_esp']} peças (saem antes da entrega) |")
w(f"| Palitos na ponte | {res['palitos_ponte']} |")
w(f"| Palitos dos espaçadores | {res['palitos_esp']} |")
w(f"| Palitos para ensaios de material | {res['palitos_ensaio']} |")
w(f"| **Palitos a comprar** (com 15% de perda) | **{res['palitos_comprar']}** |")
w(f"| Área colada | {f(res['area_cola_cm2'])} cm² |")
w(f"| Cola na ponte | {f(res['cola_g'])} g; comprar ao menos {f(res['cola_comprar_g'])} g |")
w("")
w("Os tipos com mais peças:")
w("")
w("| código | peça | comprimento (mm) | quantidade |")
w("|---|---|---|---|")
for t in sorted(tipos, key=lambda t: -t["qtd"])[:8]:
    w(f"| {t['cod']} | {t['nome_cat']} | {f(t['L'], 1)} | {t['qtd']} |")
w("")
w("## 13. Riscos e pendências")
w("")
A_t = 5.0 * eg.B
w("1. **τ da cola [PENDENTE ensaio]**: governa os consolos e as ligações. Teste caseiro: colar dois palitos com só 5 mm de sobreposição")
w(f"   ({f(A_t, 1)} mm²), esperar 24 h, pendurar um balde e encher de água aos poucos até soltar. τ = massa (kg) × {f(G)} ÷ {f(A_t, 1)}.")
w(f"   Com τ = 2,0 MPa, deve soltar perto de {f(TAU * A_t / G, 2)} kg. Se soltar antes, avise: o reforço é aumentar os consolos.")
w("2. **Propriedades do lote**: E, f_t e f_c são de literatura. A folga sobre o bônus (fator 3,4) cobre uma variação grande.")
w("3. **Comprimento e prolongamento**: confirmar com a organização (item 2).")
w("4. **Data**: o regulamento diz “2ª feira, 17/11”, mas 17/11/2026 é terça. Confirmar.")
w("5. **Cura curta**: a cola branca fica bem mais forte com 24 h. Montar as treliças primeiro e deixar o ponto de carga por último.")
w("6. **Emendas comprimidas**: cortar os palitos do banzo superior em esquadro e encostar bem as pontas antes de colar.")
w("")
w("## 14. Cronograma até a entrega (17/11, 17:30)")
w("")
w("| quando | tarefa |")
w("|---|---|")
w("| Dom 15/11 | Imprimir o manual de corte e o gabarito em 100%; cortar as peças por código e escrever o número em cada uma |")
