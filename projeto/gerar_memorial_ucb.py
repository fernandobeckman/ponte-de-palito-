w("- ABNT NBR 7190: Projeto de estruturas de madeira (Pinus elliottii: f_c0, densidade, f_c90 = 0,25 f_c0).")
w("- USDA Forest Products Laboratory. *Wood Handbook* (FPL-GTR-282), 2021.")
